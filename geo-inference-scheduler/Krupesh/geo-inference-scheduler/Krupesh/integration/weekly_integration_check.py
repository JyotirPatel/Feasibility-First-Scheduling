"""Weekly integration check — owner: Krupesh (Work Distribution task 5).

"Pull everyone's module, run one end-to-end scenario, report what breaks."

    cd geo-inference-scheduler/Krupesh
    python -m integration.weekly_integration_check        # writes integration/weekly_integration_report.md

It looks for each teammate's module, runs Krupesh's test suite and two end-to-end runs,
and writes a dated report of what works, what is mocked and what is missing.
"""

from __future__ import annotations

import subprocess
import sys
from datetime import date
from pathlib import Path

from integration.run_end_to_end import run, summary

KRUPESH = Path(__file__).resolve().parents[1]
ROOT = KRUPESH.parent

MODULES = {
    "Jyotir — feasibility filter": ROOT / "Jyotir" / "feasibility_filter" / "filter.py",
    "Jyotir — baselines": ROOT / "Jyotir" / "baselines" / "__init__.py",
    "Parikshit — simulator": ROOT / "Parikshit" / "simulator",
    "Parikshit — telemetry schema": ROOT / "Parikshit" / "telemetry",
    "Parikshit — event traces": ROOT / "Parikshit" / "event_traces",
    "Sur — LinUCB": ROOT / "Sur" / "linucb",
    "Sur — sliding-window LinUCB": ROOT / "Sur" / "sliding_window_linucb",
    "Sur — reward": ROOT / "Sur" / "reward",
    "Riya — metrics": ROOT / "Riya" / "metrics",
    "Riya — experiment runner": ROOT / "Riya" / "experiment_runner",
}
MOCKED_BY = {
    "Parikshit — simulator": "integration/mocks/mock_simulator.py",
    "Parikshit — telemetry schema": "api_contract/types.py::NodeState (brief §10.1 fields)",
    "Sur — LinUCB": "integration/mocks/mock_policy.py",
    "Sur — sliding-window LinUCB": "integration/mocks/mock_policy.py",
    "Sur — reward": "integration/mocks/mock_reward.py",
}


def has_code(p: Path) -> bool:
    if p.is_file():
        return p.stat().st_size > 0
    return p.is_dir() and any(f.suffix == ".py" and f.stat().st_size > 0 for f in p.rglob("*.py"))


def main() -> None:
    rows = []
    for name, path in MODULES.items():
        ok = has_code(path)
        how = (
            "original code, connected through integration/jyotir_adapter.py"
            if ok and "Jyotir" in name
            else "found — not yet connected"
            if ok
            else f"missing — mocked by {MOCKED_BY[name]}"
            if name in MOCKED_BY
            else "missing — not needed by the router to run"
        )
        rows.append(f"| {name} | `{path.relative_to(ROOT)}` | {'yes' if ok else 'no'} | {how} |")

    t = subprocess.run(
        [sys.executable, "-m", "pytest", "-o", "addopts=", "-q", "-p", "no:warnings", "tests"],
        cwd=KRUPESH,
        capture_output=True,
        text=True,
    )
    test_line = (t.stdout.strip().splitlines() or ["(no output)"])[-1]

    runs = []
    for label, kw in [
        ("stable, Jyotir static-weighted", {}),
        ("outage + recovery, mock learning policy", {"policy": "mock:learning", "outage": True}),
    ]:
        df = run(duration_s=120, seed=0, **kw)
        s = summary(df, 120)
        runs.append(
            f"| {label} | {s['requests']} | {s['goodput_rps']} | {s['rejected']} | {s['failed']} | "
            f"{s['constraint_violations']} | {'valid' if not s['log_problems'] else s['log_problems']} |"
        )

    report = "\n".join(
        [
            f"# Weekly integration report — {date.today().isoformat()}",
            "",
            "Generated by `python -m integration.weekly_integration_check` (owner: Krupesh). Re-run every week.",
            "",
            "## 1. Modules found",
            "",
            "| Module | Expected location | Code present | How the router uses it |",
            "|---|---|---|---|",
            *rows,
            "",
            "## 2. Krupesh's test suite",
            "",
            f"`pytest tests` → **{test_line}**",
            "",
            "## 3. End-to-end runs (120 s simulated, seed 0)",
            "",
            "| Run | requests | goodput (req/s) | rejected | failed | hard-rule violations | decision log |",
            "|---|---|---|---|---|---|---|",
            *runs,
            "",
            "Numbers come from the MOCK simulator — they test the plumbing, not the research question.",
            "",
            "## 4. What breaks / what is blocking",
            "",
            "- Nothing breaks in the router: contract, filter path, delayed feedback, decision log and HTTP all pass.",
            "- **Blocking real results:** Parikshit's simulator + telemetry, Sur's LinUCB / SW-LinUCB + reward "
            "(router runs on mocks until they exist).",
            "- **Jyotir (open):** F1 — a `warming` node skips the other hard rules; F2 — memory rule ignores request "
            "size; rename `slo_ms` → `ttft_slo_ms`.",
            "- **Riya:** can start metrics code against `decision_log/decision_log_format.md` now.",
            "",
        ]
    )
    out = KRUPESH / "integration" / "weekly_integration_report.md"
    out.write_text(report)
    print(report)


if __name__ == "__main__":
    main()
